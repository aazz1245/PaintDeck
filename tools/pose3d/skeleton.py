def face(nose, toward, up=(0, -1), s=0.012):
    """由鼻子位置、臉朝的方向（-1 左、+1 右，0 正面）推眼睛和耳朵"""
    x, y = nose
    if toward == 0:  # 正面
        return {14: (x - s, y - s), 15: (x + s, y - s), 16: (x - 2.4 * s, y), 17: (x + 2.4 * s, y)}
    back = -toward
    return {14: (x + back * 0.4 * s + up[0] * s, y + up[1] * s), 15: (x + back * 0.9 * s + up[0] * s, y + up[1] * s),
            16: (x + back * 2.6 * s, y + up[1] * 0.3 * s), 17: (x + back * 2.9 * s, y + up[1] * 0.3 * s)}


def draw(people, w, h, path, stick=None):
    img = Image.new("RGB", (w, h), (0, 0, 0))
    over = Image.new("RGB", (w, h), (0, 0, 0))
    d = ImageDraw.Draw(over)
    stick = stick or max(4, round(min(w, h) / 200))
    for kp in people:
        pts = {k: (v[0] * w, v[1] * h) for k, v in kp.items()}
        for i, (a, b) in enumerate(LIMBS):
            if a in pts and b in pts:
                (x1, y1), (x2, y2) = pts[a], pts[b]
                mx, my = (x1 + x2) / 2, (y1 + y2) / 2
                length = math.hypot(x2 - x1, y2 - y1)
                ang = math.atan2(y2 - y1, x2 - x1)
                poly = []
                for t in range(0, 360, 15):  # 跟 OpenPose 一樣用細長橢圓畫肢體
                    r = math.radians(t)
                    ex, ey = length / 2 * math.cos(r), stick * math.sin(r)
                    poly.append((mx + ex * math.cos(ang) - ey * math.sin(ang), my + ex * math.sin(ang) + ey * math.cos(ang)))
                d.polygon(poly, fill=tuple(int(c * 0.6) for c in COLORS[i]))
    img = Image.blend(img, over, 1.0)
    d = ImageDraw.Draw(img)
    for kp in people:
        for k, (x, y) in kp.items():
            x, y = x * w, y * h
            d.ellipse((x - stick, y - stick, x + stick, y + stick), fill=COLORS[k])
    img.save(path)
    return path


